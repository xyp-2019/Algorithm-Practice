// 方法一：模拟
// 思路与算法

// 由于输入的两个链表都是逆序存储数字的位数的，因此两个链表中同一位置的数字可以直接相加。

// 我们同时遍历两个链表，逐位计算它们的和，并与当前位置的进位值相加。具体而言，如果当前两个链表处相应位置的数字为 n1,n2，进位值为 carry，则它们的和为 n1+n2+carry；其中，答案链表处相应位置的数字为 (n1+n2+carry)mod10，而新的进位值为 ⌊ 
// 10
// n1+n2+carry
// ​
 // ⌋。

// 如果两个链表的长度不同，则可以认为长度短的链表的后面有若干个 0 。

// 此外，如果链表遍历结束后，有 carry>0，还需要在答案链表的后面附加一个节点，节点的值为 carry。

class Solution 
{
public:
    ListNode* addTwoNumbers(ListNode* l1, ListNode* l2) 
	{
        ListNode *head = nullptr, *tail = nullptr;	// head：结果链表头节点；tail：结果链表尾节点
		
        int carry = 0;	// carry 保存进位，初始没有进位=0
		
		// 只要l1不为空 或者 l2不为空，就继续循环
        while (l1 || l2) 
		{
            int n1 = l1 ? l1->val: 0;	// 如果l1还有节点，取当前值；没有就取0
			
            int n2 = l2 ? l2->val: 0;	// 如果l2还有节点，取当前值；没有就取
			
            int sum = n1 + n2 + carry;	// 当前位总和 = l1数字 + l2数字 + 上一轮的进位
			
			// 如果结果链表还没有头节点（第一次进来）
            if (!head) 
			{
                head = tail = new ListNode(sum % 10);	// 创建第一个节点，个位数字 sum%10
            } 
			
			// 结果链表已经有节点了
			else 
			{
                tail->next = new ListNode(sum % 10);	// 在尾部新增节点，存个位
				
                tail = tail->next;	// tail指针后移，指向新的尾节点
            }
			
            carry = sum / 10;	// 计算新进位：总和除以10取整数部分
			
			// l1没遍历完，就往后走一步
            if (l1) 
			{
                l1 = l1->next;
            }
			
			// l2没遍历完，就往后走一步
            if (l2) 
			{
                l2 = l2->next;
            }
        }
		
		// 循环结束后，如果还有进位（比如最后相加进1），额外增加一个节点
        if (carry > 0) 
		{
            tail->next = new ListNode(carry);
        }
		
        return head;	// 返回结果链表的头节点
    }
};

// ## 举例子：`l1 = [2,4,3]`，`l2 = [5,6,4]`

// > 
// > 链表是逆序存储：
// > l1 代表数字 `342`，l2 代表数字 `465`，相加 `342 + 465 = 807`，输出链表`[7,0,8]`

// ### 第一轮循环：l1=2，l2=5，carry=0

// sum = 2 + 5 + 0 =7
// head 是空，新建节点`7`，head=7，tail=7
// carry = 7 / 10 = 0
// l1 走到 4，l2 走到 6

// ### 第二轮循环：l1=4，l2=6，carry=0

// sum = 4 + 6 + 0 =10
// head 已经存在，tail 后面新增节点 `10%10=0`，链表现在`7 -> 0`，tail 移到 0
// carry = 10 /10 = 1
// l1 走到 3，l2 走到 4

// ### 第三轮循环：l1=3，l2=4，carry=1

// sum =3 +4 +1 =8
// tail 后面新增节点`8`，链表`7 ->0 ->8`，tail 移到 8
// carry =8/10=0
// l1 和 l2 全部走到 nullptr，循环结束

// carry=0，不用额外新增节点，返回 head，最终链表`7→0→8`，对应 807 ✔

// ## 再举一个有末尾进位的例子：l1=[9,9], l2=[9]

// 数字：99 +9 = 108，输出链表`[8,0,1]`

// 1. 第一轮：9+9+0=18，存 8，carry=1；l1 到 9，l2 到 null
// 2. 第二轮：9+0+1=10，存 0，carry=1；l1 到 null，l2null
// 3. 循环结束，carry=1>0，尾部追加节点 1
// 最终链表`8→0→1`，代表 108。

// 复杂度分析

// 时间复杂度：O(max(m,n))，其中 m 和 n 分别为两个链表的长度。我们要遍历两个链表的全部位置，而处理每个位置只需要 O(1) 的时间。

